-- 3.1 Типи даних
-- T1 
-- Прогноз: MySQL выдаст ошибку, потому что длина имени составляет 300 символов, 
-- а VARCHAR(255) допускает максимум 255.
-- Що сталося: ERROR 1406 (22001): Data too long for column 'full_name' at row 1
-- Чому:VARCHAR(255) допускает максимум 255

-- T2
-- Прогноз: MySQL выдаст ошибку, потому что TINYINT UNSIGNED
-- допускает значения от 0 до 255, а мы пытаемся записать 300.
-- Що сталося: ERROR 1264 (22003): Out of range value for column 'daily_hours' at row 1
-- Чому: олонка daily_hours имеет тип TINYINT UNSIGNED.
-- Число 300 превышает максимально допустимое значение 255

-- T3
-- Прогноз: ySQL выдаст ошибку, потому что UNSIGNED
-- не допускает отрицательные числа, а мы пытаемся записать -1.
-- Що сталося: ERROR 1264 (22003): Out of range value for column 'daily_hours' at row 1
-- Чому: INYINT UNSIGNED хранит числа от 0 до 255.
-- Значение -1 находится за пределами допустимого диапазона.

-- T4
-- Прогноз: число 255 сохранится успешно,
-- а число 256 вызовет ошибку, потому что
-- TINYINT UNSIGNED допускает значения от 0 до 255.
-- Що сталося: При попытке записать 256 MySQL выдал ERROR 1264 (22003).
-- Чому: vacation_days имеет тип TINYINT UNSIGNED,
-- который допускает целые числа от 0 до 255.

-- T5
-- Прогноз: ySQL выдаст ошибку, потому что ENUM разрешает
-- только значения admin и employee, а manager в списке нет.
-- Що сталося: ERROR 1265 (01000): Data truncated for column 'role' at row 1
-- Чому: колонка role имеет тип ENUM('admin', 'employee').
-- Значение manager не входит в список разрешённых значений.

-- T6
-- Прогноз: MySQL выдаст ошибку, потому что
-- даты 30 февраля 2026 года не существует.
-- Що сталося: ERROR 1292 (22007): Incorrect date value: '2026-02-30' for column 'date' at row 1
-- Чому: колонка date имеет тип DATE.
-- MySQL проверяет корректность календарной даты
-- и не позволяет сохранить несуществующий день

-- T7
-- Прогноз: MySQL выдаст ошибку, потому что времени 25:00:00
-- не существует. В сутках только 24 часа.
-- Що сталося: MySQL успешно добавил запись Query OK
-- Чому: тип TIME в MySQL может хранить не только время суток,
-- но и продолжительность времени до 838:59:59.
-- Поэтому значение 25:00:00 было принято.

-- T8
-- Прогноз: MySQL выдаст ошибку, потому что BOOL
-- должен хранить только 0 (false) или 1 (true).
-- Що сталося: MySQL успешно добавил запись (Query OK)
-- Чому: BOOL в MySQL является псевдонимом TINYINT(1).
-- Он не ограничивает значения только числами 0 и 1.
-- Поэтому значение 5 было принято.

-- 3.2 Ключі
-- K1
-- Прогноз: MySQL выдаст ошибку, потому что PRIMARY KEY
-- не допускает двух пользователей с одинаковым id.
-- Що сталося: ERROR 1062 (23000): Duplicate entry '1' for key 'users.PRIMARY'
-- Чому: id является первичным ключом (PRIMARY KEY).
-- Его значение должно быть уникальным для каждой записи.
-- Пользователь с id = 1 уже существует.

-- K2
-- Прогноз: MySQL выдаст ошибку, потому что UNIQUE
-- запрещает добавлять пользователей с одинаковым email.
-- Що сталося: ERROR 1062 (23000): Duplicate entry 'kateryna@example.com' for key 'users.email'
-- Чому: колонка email имеет ограничение UNIQUE.
-- Email должен быть уникальным для каждого пользователя.
-- Такой email уже существует в таблице users.

-- K3
-- Прогноз: MySQL разрешит добавить двух пользователей
-- с api_token = NULL, несмотря на ограничение UNIQUE.
-- Що сталося: бе записи успешно добавлены.
-- У пользователей с id = 7 и id = 8 api_token равен NULL.
-- Чому: UNIQUE запрещает повторение одинаковых значений,
-- но в MySQL допускает несколько NULL.
-- NULL означает отсутствие значения.

-- K4
-- Прогноз: MySQL выдаст ошибку, потому что
-- пользователя с id = 99999 не существует.
-- Що сталося: ERROR 1452 (23000): Cannot add or update a child row:
-- a foreign key constraint fails
-- Чому: колонка user_id связана с users(id) через FOREIGN KEY.
-- Нельзя создать запись рабочего времени для несуществующего
-- пользователя. Ограничение time_entries_ibfk_1 запретило INSERT.

-- K5
-- Прогноз: MySQL разрешит удалить пользователя,
-- даже если у него есть связанные записи в time_entries.
-- Що сталося: ERROR 1451 (23000): Cannot delete or update a parent row:
-- a foreign key constraint fails
-- Чому: в таблице time_entries существуют записи,
-- связанные с пользователем через FOREIGN KEY (user_id).
-- Удаление пользователя нарушило бы целостность данных.
-- Поэтому MySQL запретил DELETE.

-- K6
-- Прогноз: MySQL выдаст ошибку, потому что
-- на пользователя с id = 1 ссылаются записи в time_entries.
-- Що сталося: ERROR 1451 (23000): Cannot delete or update a parent row:
-- a foreign key constraint fails
-- Чому: user_id в таблице time_entries связан
-- с users(id) через FOREIGN KEY.
-- Изменение id нарушило бы связь между таблицами.
-- Поскольку ON UPDATE CASCADE не настроен,
-- MySQL запретил изменение первичного ключа.

-- K7
-- Прогноз: MySQL выдаст ошибку, потому что
-- PRIMARY KEY не может содержать NULL.
-- Що сталося: ERROR 1048 (23000): Column 'id' cannot be null
-- Чому: олонка id является PRIMARY KEY,
-- поэтому не допускает NULL.
-- AUTO_INCREMENT генерирует id при добавлении записи,
-- но не разрешает установить NULL через UPDATE.

-- 3.3 Логіка
-- L1
-- Прогноз: MySQL не выдаст ошибку и сохранит запись,
-- потому что оба значения соответствуют типу DATETIME.
-- В таблице нет ограничения CHECK, которое проверяет,
-- что ended_at должен быть позже started_at.
-- Що сталося: Query OK, 1 row affected (0.01 sec)
-- Чому: оба значения являются корректными DATETIME.
-- Но в таблице нет ограничения, которое проверяет
-- логическую последовательность начала и окончания работы.
-- Поэтому удалось сохранить работу длительностью минус 9 часов.

-- L2
-- Прогноз: MySQL разрешит добавить запись,
-- потому что обе даты соответствуют типу DATE.
-- В таблице нет ограничения CHECK, которое проверяет,
-- что date_to должен быть не раньше date_from.
-- Що сталося: Query OK, 1 row affected (0.01 sec)
-- Чому: обе даты являются корректными значениями DATE.
-- Но в таблице нет ограничения, которое проверяет,
-- что дата окончания отпуска не раньше даты начала.
-- Поэтому удалось сохранить отпуск с неправильным периодом.

-- L3
-- Прогноз: MySQL выдаст ошибку, потому что
-- колонка created_by имеет ограничение NOT NULL.
-- В запросе значение created_by не указано,
-- и у колонки нет значения DEFAULT.
-- Що сталося: ERROR 1364 (HY000): Field 'created_by' doesn't have a default value
-- Чому: created_by является обязательным полем.
-- При добавлении записи сотрудником через кнопку
-- "Я пришёл" необходимо указать, кто создал запись.
-- Сейчас база данных не позволяет пропустить created_by.

-- 3.4 Висновки
-- 1. Баги схеми (усі ⚠️ Успіх):
-- T7: work_start позволяет сохранить 25:00:00.
-- T8: is_active позволяет сохранить значение 5.
-- L1: ended_at может быть раньше started_at.
-- L2: date_to может быть раньше date_from.
-- Эти ошибки возникают из-за отсутствия дополнительных
-- ограничений, проверяющих бизнес-логику.

-- 2. Чому не видалилась users? Чи треба видаляти звільнених?
-- Пользователь не удалился из-за FOREIGN KEY.
-- На него ссылаются записи в таблице time_entries.
-- Уволенных сотрудников лучше не удалять,
-- а устанавливать is_active = 0.
-- Это позволит сохранить историю рабочего времени и отпусков.

-- 3. created_by: мій варіант (а/б) і чому:
-- Я выбираю вариант (а).
-- В created_by всегда должен храниться id пользователя,
-- который создал запись.
-- Если сотрудник сам отметил приход, created_by = user_id.
-- Если запись создал администратор, created_by = id администратора.
-- Так можно определить, кто именно создал каждую запись.
-- Кроме того, этот вариант соответствует текущей схеме,
-- где created_by имеет ограничение NOT NULL.

