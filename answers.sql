-- 1.5 Питання
-- BIGINT vs INT:
-- Для users.id используется INT, так как количество пользователей
-- относительно небольшое.
-- Для time_entries.id используется BIGINT, потому что каждый сотрудник
-- создаёт много записей рабочего времени, и их количество постоянно растёт.

-- ended_at, поки людина на роботі:
-- Пока сотрудник находится на работе, в ended_at хранится NULL.
-- Это означает, что время окончания работы ещё не указано.
-- Когда сотрудник завершит работу, в ended_at запишется
-- дата и время его ухода.

-- Індекси в users і звідки їхні імена:
-- В таблице users есть 4 индекса:
-- PRIMARY (id) — первичный ключ, имя задаётся MySQL.
-- email (email) — уникальный индекс, имя создано автоматически.
-- api_token (api_token) — уникальный индекс, имя создано автоматически.
-- idx_fulltext_full_name (full_name) — полнотекстовый индекс,
-- его название явно указано в миграции 001_create_users.sql.

-- Імена зовнішніх ключів у time_entries:
-- MySQL автоматически создал два внешних ключа:
-- time_entries_ibfk_1 — связывает user_id с users.id.
-- time_entries_ibfk_2 — связывает created_by с users.id.
-- Названия присвоены автоматически, так как мы не указали их сами.

